#[cfg(test)]
mod tests {
    use super::*;

    /// The bar is CotEditor's, in CotEditor's order, with the application
    /// menu renamed. Nothing else may drift.
    #[test]
    fn the_bar_has_every_top_level_menu() {
        assert_eq!(app_menus(&crate::menus::MenuGates::default()).len(), 10);
        let names: Vec<_> = app_menus(&crate::menus::MenuGates::default())
            .iter()
            .map(|menu| menu.name.to_string())
            .collect();
        assert_eq!(
            names,
            [
                "SubText",
                "File",
                "Edit",
                "Format",
                "View",
                "Text",
                "Find",
                "Window",
                "Script",
                "Help",
            ]
        );
    }

    /// A menu item whose action nothing handles is greyed out by GPUI, so
    /// every *leaf* has to name a real action — even the placeholders that
    /// stay placeholders, which say `NoOp` and disable themselves.
    ///
    /// The empty submenus are counted as nothing, not as one item each: the
    /// runtime fills them in, and a test that counted them would go on
    /// passing if one of them were never filled.
    #[test]
    fn every_item_has_an_action() {
        fn count(menu: &Menu) -> usize {
            menu.items
                .iter()
                .map(|item| match item {
                    MenuItem::Submenu(inner) => count(inner),
                    MenuItem::Action { .. } => 1,
                    _ => 0,
                })
                .sum()
        }
        let total: usize = app_menus(&crate::menus::MenuGates::default()).iter().map(count).sum();
        assert_eq!(total, 172);
    }

    /// Every command the bar can offer is one the menu bar has.
    ///
    /// The two tables come from one source, so a command that went
    /// missing from either would be a generator bug rather than a typo.
    #[test]
    fn the_command_table_is_the_whole_menu() {
        assert_eq!(COMMANDS.len(), 168);
        let mut paths: Vec<_> = COMMANDS.iter().map(|c| c.path).collect();
        paths.sort_unstable();
        paths.dedup();
        assert_eq!(paths.len(), COMMANDS.len(), "a path names two commands");
        for command in COMMANDS {
            assert!(!command.path.is_empty());
            assert!(!command.action.is_empty());
        }
    }

    /// A shortcut belongs to a command, so its path has to be one of ours.
    ///
    /// This is the join [`crate::menus::shortcut`] makes to draw a
    /// shortcut beside a result: if the two tables spelled a path
    /// differently the join would silently find nothing and the bar
    /// would show no key.
    #[test]
    fn every_shortcut_belongs_to_a_listed_command() {
        for row in crate::keymap::SHORTCUTS {
            assert!(
                COMMANDS.iter().any(|command| command.path == row.0),
                "{} has no command",
                row.0
            );
        }
    }
}
