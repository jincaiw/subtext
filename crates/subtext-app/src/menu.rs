#[cfg(test)]
mod tests {
    use super::*;

    /// The bar is CotEditor's, in CotEditor's order, with the application
    /// menu renamed. Nothing else may drift.
    #[test]
    fn the_bar_has_every_top_level_menu() {
        assert_eq!(app_menus().len(), 10);
        let names: Vec<_> = app_menus()
            .iter()
            .map(|menu| menu.name.to_string())
            .collect();
        assert_eq!(
            names,
            [
                "SubText",
                "File",
                "Edit",
                "Format",
                "View",
                "Text",
                "Find",
                "Window",
                "Script",
                "Help",
            ]
        );
    }

    /// A menu item whose action nothing handles is greyed out by GPUI, so
    /// every item has to name a real action — even the placeholders, which
    /// say `NoOp` and disable themselves.
    #[test]
    fn every_item_has_an_action() {
        fn count(menu: &Menu) -> usize {
            menu.items
                .iter()
                .map(|item| match item {
                    MenuItem::Submenu(inner) => count(inner),
                    MenuItem::Action { .. } => 1,
                    _ => 0,
                })
                .sum()
        }
        let total: usize = app_menus().iter().map(count).sum();
        assert_eq!(total, 178);
    }
}
