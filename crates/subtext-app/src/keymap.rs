/// Shortcuts CotEditor assigns twice, kept visible rather than silently
/// resolved. macOS settles them by menu order; so do we.
pub const KNOWN_COLLISIONS: &[(&str, &str, &str)] = &[];

#[cfg(test)]
mod tests {
    use super::*;

    /// Every binding has to survive GPUI's keystroke parser.
    ///
    /// `KeyBinding::new` panics on a keystroke it cannot read, and it
    /// reads far less than it looks like it does — `control-` is a key
    /// named `control`, not the Control modifier, so a table written with
    /// the wrong spelling takes the whole application down at launch
    /// rather than at the first keypress. Building the table is the test.
    #[test]
    fn every_binding_parses() {
        assert_eq!(default_bindings().len(), 75);
    }

    /// Two commands on one keystroke is a bug unless it is CotEditor's bug.
    ///
    /// The generator reports collisions in binding terms when it writes
    /// [`KNOWN_COLLISIONS`]; this test is what fails when a regeneration
    /// finds one that has not been acknowledged.
    #[test]
    fn collisions_are_the_ones_we_know_about() {
        assert_eq!(KNOWN_COLLISIONS.len(), 0);
    }

    /// The Key Bindings pane lists the same table the key map is built from.
    #[test]
    fn the_shortcut_table_matches_the_bindings() {
        let bindings = default_bindings();
        assert_eq!(bindings.len(), SHORTCUTS.len());
        for row in SHORTCUTS {
            assert!(!row.0.is_empty(), "every shortcut belongs to a menu item");
            assert!(!row.1.is_empty(), "{} has no shortcut", row.0);
        }
    }

    /// The table's last field is the keystroke the key map really binds.
    ///
    /// That is what makes it usable as the answer to "is this shortcut
    /// taken?": a table row and a binding that disagreed would name one
    /// command and reserve another, which is exactly the bug the Snippets
    /// pane's shortcut field exists to prevent.
    #[test]
    fn the_table_holds_the_keystrokes_the_key_map_binds() {
        for (binding, row) in default_bindings().iter().zip(SHORTCUTS) {
            let typed = gpui_kit::Keystroke::parse_with_os(row.4, crate::host_os()).expect(row.4);
            assert_eq!(
                binding.match_keystrokes(&[typed]),
                Some(false),
                "{} binds {}",
                row.0,
                row.4
            );
        }
    }

    /// No two commands answer to one keystroke on this platform.
    ///
    /// The storyboard has no duplicates on macOS, but the translation to
    /// Windows and Linux is not a rename — Command becomes Control there,
    /// so a Cocoa Control left alone would fold into it (⌃⌘F into ⌘F, which
    /// would shadow Find). This is the test that fails when that happens,
    /// on whichever platform runs it.
    #[test]
    fn no_two_shortcuts_share_a_keystroke_here() {
        let parsed: Vec<_> = SHORTCUTS
            .iter()
            .map(|row| gpui_kit::Keystroke::parse_with_os(row.4, crate::host_os()).expect(row.4))
            .collect();
        for (index, first) in parsed.iter().enumerate() {
            for (other, second) in parsed.iter().enumerate().skip(index + 1) {
                assert_ne!(
                    first, second,
                    "{} and {} both answer to {}",
                    SHORTCUTS[index].0, SHORTCUTS[other].0, SHORTCUTS[index].4
                );
            }
        }
    }
}
