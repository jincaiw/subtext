// tools/generate_unicode_tables.swift
//
// Writes `crates/subtext-core/src/unicode_tables.rs`.
//
// The **Inspect Character** panel shows three Unicode properties that neither
// the Rust standard library nor any crate already in the tree exposes:
// `age` (which Unicode version assigned the scalar), `isDeprecated`, and
// `isVariationSelector`. Swift's standard library has all three — and it is the
// same source CotEditor reads, through `Unicode.Scalar.Properties` — so the
// table is generated from it rather than transcribed from `DerivedAge.txt` by
// hand.
//
// Two more tables come from here for the same reason: **NFKC Case-Fold** needs
// Unicode's full case folding and the `Default_Ignorable_Code_Point` property,
// and Foundation is where upstream gets both (`String.folding(options:
// .caseInsensitive)` and `\p{Default_Ignorable_Code_Point}`). Measuring them
// against the same implementation is the only way the two editors agree.
//
// Usage:
//
//     swiftc -O tools/generate_unicode_tables.swift -o /tmp/gen_tables
//     /tmp/gen_tables crates/subtext-core/src/unicode_tables.rs
//
// The output is committed, so building SubText does not need Swift. Re-run this
// after a Swift toolchain update that moves the Unicode version.

import Foundation

// MARK: - Scanning

/// One maximal run of scalars that share a property value.
struct Run<Value> {
    var start: UInt32
    var end: UInt32
    var value: Value
}

/// Every maximal run over the whole code space, in order.
///
/// A scalar the property does not apply to ends the run in progress and starts
/// none, so the gaps between runs are exactly the scalars without a value.
func runs<Value: Equatable>(_ value: (Unicode.Scalar) -> Value?) -> [Run<Value>] {
    var found: [Run<Value>] = []
    var open: Run<Value>?
    var code: UInt32 = 0
    while code <= 0x10FFFF {
        let current = Unicode.Scalar(code).flatMap(value)
        switch (open, current) {
            case (nil, nil):
                break
            case (nil, let value?):
                open = Run(start: code, end: code, value: value)
            case (var run?, let value?):
                if run.value == value, run.end &+ 1 == code {
                    run.end = code
                    open = run
                } else {
                    found.append(run)
                    open = Run(start: code, end: code, value: value)
                }
            case (let run?, nil):
                found.append(run)
                open = nil
        }
        code += 1
    }
    if let run = open { found.append(run) }
    return found
}

// MARK: - Emitting

/// `1.1` → `0x11`; a byte keeps the table small and the comparison cheap.
func packed(_ major: Int, _ minor: Int) -> Int {
    major * 16 + minor
}

let header = """
//! Unicode property tables: the **Character** section's properties, the version
//! of Unicode each scalar arrived in, and the two tables **NFKC Case-Fold**
//! needs (the full case fold and `Default_Ignorable_Code_Point`).
//!
//! Generated by `tools/generate_unicode_tables.swift` — see that file for why
//! the source is Swift's own Unicode tables. **Do not edit by hand.**
//!
//! Each table is a list of maximal runs: consecutive scalars sharing a value
//! are one entry, and a lookup is a binary search over the starts.
"""

var out = header

/// Writes one `const` table and the lookup that reads it.
func emit<Value>(
    _ name: String,
    _ type: String,
    _ doc: String,
    _ runs: [Run<Value>],
    _ render: (Value) -> String
) {
    out += "\n/// \(doc)\n"
    out += "const \(name): &[(u32, u32, \(type))] = &[\n"
    for run in runs {
        let start = String(format: "0x%04X", run.start)
        let end = String(format: "0x%04X", run.end)
        out += "    (\(start), \(end), \(render(run.value))),\n"
    }
    out += "];\n"
    out += "\n/// The entry of [`\(name)`] containing `value`, by binary search.\n"
    out += "fn \(name.lowercased())_at(value: u32) -> Option<\(type)> {\n"
    out += "    let index = \(name).partition_point(|(start, _, _)| *start <= value);\n"
    out += "    let (_, end, found) = *\(name).get(index.checked_sub(1)?)?;\n"
    out += "    (value <= end).then_some(found)\n"
    out += "}\n"
}

let age = runs { $0.properties.age.map { packed($0.major, $0.minor) } }
let deprecated = runs { $0.properties.isDeprecated ? true : nil }
let variation = runs { $0.properties.isVariationSelector ? true : nil }

/// The property upstream's `removingDefaultIgnorableCodePoints` matches.
///
/// Swift's `Unicode.Scalar.Properties` has no accessor for it, so this asks the
/// same regular expression engine upstream uses — one scalar at a time, which
/// over the whole code space costs half a second.
let ignorableRegex = try! Regex("\\p{Default_Ignorable_Code_Point}")
let defaultIgnorable = runs { scalar in
    let one = String(Character(scalar))
    return one.wholeMatch(of: ignorableRegex) != nil ? true : nil
}

emit(
    "AGE",
    "u16",
    "`Unicode.Scalar.Properties.age`, packed as `major * 16 + minor` — a `u16`\n/// because Unicode 17.0 packs to 272, past what a byte holds. A scalar Unicode\n/// has not assigned has no entry, which is also what the panel shows: an\n/// empty Version row.",
    age,
    { "0x\(String($0, radix: 16, uppercase: true))" }
)

out += """

/// The Unicode version that assigned `value`, as `(major, minor)`.
pub fn age(value: u32) -> Option<(u8, u8)> {
    let packed = age_at(value)?;
    Some(((packed >> 4) as u8, (packed & 0xF) as u8))
}
"""

emit(
    "DEPRECATED",
    "bool",
    "`Unicode.Scalar.Properties.isDeprecated`.",
    deprecated,
    { $0 ? "true" : "false" }
)

emit(
    "VARIATION_SELECTOR",
    "bool",
    "`Unicode.Scalar.Properties.isVariationSelector`.",
    variation,
    { $0 ? "true" : "false" }
)

emit(
    "DEFAULT_IGNORABLE",
    "bool",
    "The `Default_Ignorable_Code_Point` property, which NFKC Case-Fold removes\n/// before and after normalizing — upstream matches it with a regular expression.",
    defaultIgnorable,
    { $0 ? "true" : "false" }
)

/// Every scalar whose full case fold differs from itself.
///
/// Measured, not transcribed: `String.folding(options: .caseInsensitive)` is
/// what upstream calls, and it is Unicode's full folding (C + F) rather than
/// lower-casing — `ß` folds to `ss`, `ς` to `σ`, `İ` to `i` + U+0307.
let caseFold: [(UInt32, String)] = (0...0x10FFFF as ClosedRange<UInt32>).compactMap { code in
    guard let scalar = Unicode.Scalar(code) else { return nil }
    let one = String(Character(scalar))
    let folded = one.folding(options: .caseInsensitive, locale: nil)
    return folded == one ? nil : (code, folded)
}

/// A Swift string as a Rust literal, with everything outside printable ASCII
/// escaped — many entries are combining sequences that would be invisible in a
/// diff otherwise.
func rustString(_ text: String) -> String {
    var out = "\""
    for scalar in text.unicodeScalars {
        switch scalar {
            case "\\": out += "\\\\"
            case "\"": out += "\\\""
            default:
                if scalar.value >= 0x20 && scalar.value < 0x7F {
                    out.unicodeScalars.append(scalar)
                } else {
                    out += String(format: "\\u{%X}", scalar.value)
                }
        }
    }
    return out + "\""
}

out += "\n/// Unicode's full case folding — the C and F mappings of `CaseFolding.txt`,\n"
out += "/// one entry per scalar that folds to something other than itself.\n"
out += "const CASE_FOLD: &[(u32, &str)] = &[\n"
for (code, folded) in caseFold {
    out += "    (0x\(String(format: "%04X", code)), \(rustString(folded))),\n"
}
out += "];\n"

out += """

/// Whether Unicode has deprecated `value`.
pub fn is_deprecated(value: u32) -> bool {
    deprecated_at(value).unwrap_or(false)
}

/// Whether `value` is a variation selector.
pub fn is_variation_selector(value: u32) -> bool {
    variation_selector_at(value).unwrap_or(false)
}

/// Whether `value` is default-ignorable.
pub fn is_default_ignorable(value: u32) -> bool {
    default_ignorable_at(value).unwrap_or(false)
}

/// The full case fold of `value`, or `None` when it folds to itself.
pub fn case_fold(value: u32) -> Option<&'static str> {
    let index = CASE_FOLD.partition_point(|(start, _)| *start <= value);
    let (found, folded) = *CASE_FOLD.get(index.checked_sub(1)?)?;
    (found == value).then_some(folded)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The runs are generated, so this is the check that the generator did not
    /// drop one, overlap two, or run one backwards.
    #[test]
    fn the_runs_are_ascending_and_do_not_overlap() {
        for (index, table) in [
            AGE.len(),
            DEPRECATED.len(),
            VARIATION_SELECTOR.len(),
            DEFAULT_IGNORABLE.len(),
        ]
        .into_iter()
        .enumerate()
        {
            assert!(table > 0, "table {index} is empty");
        }
        let mut previous = None;
        for &(start, end, _) in AGE {
            assert!(start <= end);
            if let Some(previous_end) = previous {
                assert!(start > previous_end, "overlap at {start:#06X}");
            }
            previous = Some(end);
        }
        // The fold table is not runs but one entry per scalar, so the check is
        // strict ordering rather than non-overlap.
        assert!(CASE_FOLD.len() > 1000, "the fold table looks truncated");
        let mut previous = None;
        for &(code, _) in CASE_FOLD {
            if let Some(previous) = previous {
                assert!(code > previous, "fold table out of order at {code:#06X}");
            }
            previous = Some(code);
        }
    }

    /// Spot checks against values taken from `DerivedAge.txt` and `PropList.txt`.
    #[test]
    fn a_few_known_values() {
        assert_eq!(age(0x0041), Some((1, 1)));
        assert_eq!(age(0x20AC), Some((2, 1)));
        assert_eq!(age(0x1F600), Some((6, 1)));
        assert_eq!(age(0x31350), Some((15, 0)));
        assert_eq!(age(0x323B0), Some((17, 0)));
        // An unassigned scalar has no version, which is the empty row. The
        // private-use planes are assigned — they are 2.0 — so the example has
        // to be a real gap in Unicode's coverage.
        assert_eq!(age(0x34000), None);

        assert!(is_deprecated(0x0149));
        assert!(is_deprecated(0xE0001));
        assert!(!is_deprecated(0x0041));

        assert!(is_variation_selector(0xFE0F));
        assert!(is_variation_selector(0xE0100));
        assert!(!is_variation_selector(0x0041));

        // Soft hyphen, ZWJ, BOM and the tag block are; a combining accent and
        // an ordinary letter are not.
        assert!(is_default_ignorable(0x00AD));
        assert!(is_default_ignorable(0x200D));
        assert!(is_default_ignorable(0xFEFF));
        assert!(is_default_ignorable(0xE0041));
        assert!(!is_default_ignorable(0x0301));
        assert!(!is_default_ignorable(0x0041));
    }

    /// The fold mappings that tell full folding apart from lower-casing.
    #[test]
    fn a_few_known_folds() {
        assert_eq!(case_fold(0x00DF), Some("ss")); // ß
        assert_eq!(case_fold(0x1E9E), Some("ss")); // ẞ
        assert_eq!(case_fold(0x03C2), Some("\\u{3C3}")); // ς → σ, not itself
        assert_eq!(case_fold(0x0130), Some("i\\u{307}")); // İ → i + combining dot
        assert_eq!(case_fold(0x0041), Some("a"));
        // A character that folds to itself has no entry, and one that never
        // had a case (a digit) has none either.
        assert_eq!(case_fold(0x0061), None);
        assert_eq!(case_fold(0x0031), None);
    }
}
"""

// MARK: - Writing

let arguments = CommandLine.arguments
guard arguments.count == 2 else {
    FileHandle.standardError.write("usage: gen_tables <output.rs>\n".data(using: .utf8)!)
    exit(2)
}

let url = URL(fileURLWithPath: arguments[1])
try out.write(to: url, atomically: true, encoding: .utf8)

let summary = """
wrote \(url.path)
  age:                \(age.count) ranges
  deprecated:         \(deprecated.count) ranges
  variation selector: \(variation.count) ranges
  default ignorable:  \(defaultIgnorable.count) ranges
  case fold:          \(caseFold.count) mappings
"""
