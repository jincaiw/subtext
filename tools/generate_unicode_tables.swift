// tools/generate_unicode_tables.swift
//
// Writes `crates/subtext-core/src/unicode_tables.rs`.
//
// The **Inspect Character** panel shows three Unicode properties that neither
// the Rust standard library nor any crate already in the tree exposes:
// `age` (which Unicode version assigned the scalar), `isDeprecated`, and
// `isVariationSelector`. Swift's standard library has all three — and it is the
// same source CotEditor reads, through `Unicode.Scalar.Properties` — so the
// table is generated from it rather than transcribed from `DerivedAge.txt` by
// hand.
//
// Usage:
//
//     swiftc -O tools/generate_unicode_tables.swift -o /tmp/gen_tables
//     /tmp/gen_tables crates/subtext-core/src/unicode_tables.rs
//
// The output is committed, so building SubText does not need Swift. Re-run this
// after a Swift toolchain update that moves the Unicode version.

import Foundation

// MARK: - Scanning

/// One maximal run of scalars that share a property value.
struct Run<Value> {
    var start: UInt32
    var end: UInt32
    var value: Value
}

/// Every maximal run over the whole code space, in order.
///
/// A scalar the property does not apply to ends the run in progress and starts
/// none, so the gaps between runs are exactly the scalars without a value.
func runs<Value: Equatable>(_ value: (Unicode.Scalar) -> Value?) -> [Run<Value>] {
    var found: [Run<Value>] = []
    var open: Run<Value>?
    var code: UInt32 = 0
    while code <= 0x10FFFF {
        let current = Unicode.Scalar(code).flatMap(value)
        switch (open, current) {
            case (nil, nil):
                break
            case (nil, let value?):
                open = Run(start: code, end: code, value: value)
            case (var run?, let value?):
                if run.value == value, run.end &+ 1 == code {
                    run.end = code
                    open = run
                } else {
                    found.append(run)
                    open = Run(start: code, end: code, value: value)
                }
            case (let run?, nil):
                found.append(run)
                open = nil
        }
        code += 1
    }
    if let run = open { found.append(run) }
    return found
}

// MARK: - Emitting

/// `1.1` → `0x11`; a byte keeps the table small and the comparison cheap.
func packed(_ major: Int, _ minor: Int) -> Int {
    major * 16 + minor
}

let header = """
//! Unicode property tables for the **Character** section, and the version of
//! Unicode each scalar arrived in.
//!
//! Generated by `tools/generate_unicode_tables.swift` — see that file for why
//! the source is Swift's own Unicode tables. **Do not edit by hand.**
//!
//! Each table is a list of maximal runs: consecutive scalars sharing a value
//! are one entry, and a lookup is a binary search over the starts.
"""

var out = header

/// Writes one `const` table and the lookup that reads it.
func emit<Value>(
    _ name: String,
    _ type: String,
    _ doc: String,
    _ runs: [Run<Value>],
    _ render: (Value) -> String
) {
    out += "\n/// \(doc)\n"
    out += "const \(name): &[(u32, u32, \(type))] = &[\n"
    for run in runs {
        let start = String(format: "0x%04X", run.start)
        let end = String(format: "0x%04X", run.end)
        out += "    (\(start), \(end), \(render(run.value))),\n"
    }
    out += "];\n"
    out += "\n/// The entry of [`\(name)`] containing `value`, by binary search.\n"
    out += "fn \(name.lowercased())_at(value: u32) -> Option<\(type)> {\n"
    out += "    let index = \(name).partition_point(|(start, _, _)| *start <= value);\n"
    out += "    let (_, end, found) = *\(name).get(index.checked_sub(1)?)?;\n"
    out += "    (value <= end).then_some(found)\n"
    out += "}\n"
}

let age = runs { $0.properties.age.map { packed($0.major, $0.minor) } }
let deprecated = runs { $0.properties.isDeprecated ? true : nil }
let variation = runs { $0.properties.isVariationSelector ? true : nil }

emit(
    "AGE",
    "u16",
    "`Unicode.Scalar.Properties.age`, packed as `major * 16 + minor` — a `u16`\n/// because Unicode 17.0 packs to 272, past what a byte holds. A scalar Unicode\n/// has not assigned has no entry, which is also what the panel shows: an\n/// empty Version row.",
    age,
    { "0x\(String($0, radix: 16, uppercase: true))" }
)

out += """

/// The Unicode version that assigned `value`, as `(major, minor)`.
pub fn age(value: u32) -> Option<(u8, u8)> {
    let packed = age_at(value)?;
    Some(((packed >> 4) as u8, (packed & 0xF) as u8))
}
"""

emit(
    "DEPRECATED",
    "bool",
    "`Unicode.Scalar.Properties.isDeprecated`.",
    deprecated,
    { $0 ? "true" : "false" }
)

emit(
    "VARIATION_SELECTOR",
    "bool",
    "`Unicode.Scalar.Properties.isVariationSelector`.",
    variation,
    { $0 ? "true" : "false" }
)

out += """

/// Whether Unicode has deprecated `value`.
pub fn is_deprecated(value: u32) -> bool {
    deprecated_at(value).unwrap_or(false)
}

/// Whether `value` is a variation selector.
pub fn is_variation_selector(value: u32) -> bool {
    variation_selector_at(value).unwrap_or(false)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The runs are generated, so this is the check that the generator did not
    /// drop one, overlap two, or run one backwards.
    #[test]
    fn the_runs_are_ascending_and_do_not_overlap() {
        for (index, table) in [AGE.len(), DEPRECATED.len(), VARIATION_SELECTOR.len()]
            .into_iter()
            .enumerate()
        {
            assert!(table > 0, "table {index} is empty");
        }
        let mut previous = None;
        for &(start, end, _) in AGE {
            assert!(start <= end);
            if let Some(previous_end) = previous {
                assert!(start > previous_end, "overlap at {start:#06X}");
            }
            previous = Some(end);
        }
    }

    /// Spot checks against values taken from `DerivedAge.txt` and `PropList.txt`.
    #[test]
    fn a_few_known_values() {
        assert_eq!(age(0x0041), Some((1, 1)));
        assert_eq!(age(0x20AC), Some((2, 1)));
        assert_eq!(age(0x1F600), Some((6, 1)));
        assert_eq!(age(0x31350), Some((15, 0)));
        assert_eq!(age(0x323B0), Some((17, 0)));
        // An unassigned scalar has no version, which is the empty row. The
        // private-use planes are assigned — they are 2.0 — so the example has
        // to be a real gap in Unicode's coverage.
        assert_eq!(age(0x34000), None);

        assert!(is_deprecated(0x0149));
        assert!(is_deprecated(0xE0001));
        assert!(!is_deprecated(0x0041));

        assert!(is_variation_selector(0xFE0F));
        assert!(is_variation_selector(0xE0100));
        assert!(!is_variation_selector(0x0041));
    }
}
"""

// MARK: - Writing

let arguments = CommandLine.arguments
guard arguments.count == 2 else {
    FileHandle.standardError.write("usage: gen_tables <output.rs>\n".data(using: .utf8)!)
    exit(2)
}

let url = URL(fileURLWithPath: arguments[1])
try out.write(to: url, atomically: true, encoding: .utf8)

let summary = """
wrote \(url.path)
  age:                \(age.count) ranges
  deprecated:         \(deprecated.count) ranges
  variation selector: \(variation.count) ranges
"""
print(summary)
